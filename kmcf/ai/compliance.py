    + _CLAUSE + r"{0,30}(?:建议|推荐|预测|依据|判断|指导|目标价|时机|买卖点|荐股)",
    r"(?:并非|不是|非)" + _CLAUSE + r"{0,12}(?:投资|操作|买卖)(?:建议|依据|推荐)",
    r"(?:不|无法|不能|不会|不再)(?:去)?(?:预测|预判|推测|判断)(?:明[天日]|下周|后市|未来|之后)?的?"
