    r"(?:轻仓|半仓|满仓|空仓|仓位)[^。；！？\n，,]{0,4}?"
    r"(?:参与|操作|应对|观望|为主|等待|介入|不超过|不宜|降至|提升至|提高至|加到|减到|[一二三四五六七八九十半]成)",
    r"(?:设置|设好|及时|严格|做好|注意|适时|执行)(?:止损|止盈)",
    r"(?:抄底|低吸|追涨|追高|交易|投资|买入|介入|参与|配置|短线|波段|套利|结构性)(?:机会|时机|良机)",
    # 荐股 / 价格判断
    r"值得(?:买|卖|持有|关注|布局|配置|介入|参与|期待|拥有|入手)",
    r"(?:重点|密切)关注",
    r"(?:上看|剑指)\s*\d",
    r"翻倍(?:空间|潜力|机会|行情|股)",
